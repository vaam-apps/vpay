const ANSWER_JSON: &str = r#"{"id":"cus_golden","object":"customer"}"#;

fn public_of(seed: &[u8; 32]) -> [u8; 32] {
    Ed25519Signer::from_seed(seed)
        .verify_key()
        .ed25519_bytes()
        .expect("an Ed25519 key")
}

#[derive(Debug, Clone, Copy)]
struct CustomersOnly;

impl BindingResolver for CustomersOnly {
    fn resolve(&self, request: &RouteRequest<'_>) -> Resolution {
        if request.method().as_str() == "POST" && request.path() == "/v1/customers" {
            Resolution::Op(
                ResolvedRoute::new("/customers", Vec::<String>::new())
                    .with_contract_key("POST /customers".to_owned())
                    .with_payload_types(&[FORM], &["application/json"]),
            )
        } else {
            Resolution::NotAnOp
        }
    }
}

/// The merchant's side at the pinned clock and `cti`.
fn client_envelope(merchant_seed: &[u8; 32]) -> ClientEnvelope {
    let resolver = StaticVerifierResolver::new()
        .with_key(CoseVerifyKey::ed25519(&public_of(&SERVER_SEED)).expect("a point"));
    let cose = CoseEnvelope::client(
        CoseMode::Sign1,
        Arc::new(Ed25519Signer::from_seed(merchant_seed)),
        Arc::new(resolver),
    )
    .clock(|| NOW)
    .cti_source(|| Ok(CTI.to_vec()))
    .build()
    .expect("a client envelope");
    ClientEnvelope::new(cose, AUDIENCE.to_owned()).expect("an audience")
}

struct Sealed {
    headers: Vec<(String, String)>,
    body: Vec<u8>,
    pending: PendingResponse,
}

async fn seal(merchant_seed: &[u8; 32]) -> Sealed {
    let call = SealCall::new(
        "POST",
        RouteRef::new("/customers", &[]),
        contract_digest("POST", "/customers"),
    )
    .payload(BODY.as_bytes(), FORM)
    .accept("application/json")
    .idempotency_key("idem_golden");
    let sealed = client_envelope(merchant_seed)
        .seal_call(call)
        .await
        .expect("the call seals");
    let mut headers: Vec<(String, String)> = sealed
        .headers
        .iter()
        .map(|(n, v)| (n.to_string(), v.to_str().expect("ascii").to_owned()))
        .collect();
    headers.sort();
    Sealed {
        headers,
        body: sealed.body.to_vec(),
        pending: sealed.pending,
    }
}

/// What the handler behind the layer saw: the opened, plain form request.
type Seen = Arc<Mutex<Vec<(String, String)>>>;

/// The server's side: the real `EnvelopeLayer` in `Required` mode, as `vpay-api`
/// mounts it, with a verifier clock of `now` and a replay cache that lives as
/// long as the returned router.
fn server(now: i64, merchant_key: [u8; 32], seen: Seen) -> Router {
    let envelope = CoseEnvelope::server(
        CoseMode::Sign1,
        Arc::new(Ed25519Signer::from_seed(&SERVER_SEED)),
        Arc::new(
            StaticVerifierResolver::new()
                .with_key(CoseVerifyKey::ed25519(&merchant_key).expect("a point")),
        ),
        Arc::new(InMemoryNonceStore::new()),
    )
    .clock(move || now)
    .build()
    .expect("a server envelope");
    let digests: &'static [[u8; 32]] = Box::leak(Box::new([contract_digest("POST", "/customers")]));
    let rows: &'static [(&'static str, &'static [[u8; 32]])] =
        Box::leak(Box::new([("POST /customers", digests)]));
    let contracts: AcceptedContracts = rows;
    let layer: EnvelopeLayer = EnvelopeLayer::builder(envelope, AUDIENCE.to_owned(), contracts)
        .binding_resolver(CustomersOnly)
        .policy(EnvelopeMode::Required)
        .payload_media_types([FORM], ["application/json"])
        .build()
        .expect("the layer builds");
    Router::new()
        .fallback(move |request: Request<Body>| {
            let seen = Arc::clone(&seen);
            async move {
                let (parts, body) = request.into_parts();
                let bytes = axum::body::to_bytes(body, 1 << 20).await.expect("a body");
                let mut saw = seen.lock().expect("lock");
                saw.push(("path".to_owned(), parts.uri.path().to_owned()));
                for name in ["content-type", "idempotency-key"] {
                    if let Some(value) = parts.headers.get(name) {
                        saw.push((name.to_owned(), value.to_str().expect("ascii").to_owned()));
                    }
                }
                saw.push((
                    "body".to_owned(),
                    String::from_utf8(bytes.to_vec()).expect("utf8"),
                ));
                Response::builder()
                    .status(StatusCode::CREATED)
                    .header("content-type", "application/json")
                    .body(Body::from(ANSWER_JSON))
                    .expect("a response")
            }
        })
        .layer(layer)
}

struct Answer {
    status: u16,
    headers: Vec<(String, String)>,
    body: Vec<u8>,
}

fn sorted(headers: &HeaderMap) -> Vec<(String, String)> {
    let mut out: Vec<_> = headers
        .iter()
        .map(|(n, v)| (n.to_string(), v.to_str().expect("ascii").to_owned()))
        .collect();
    out.sort();
    out
}

async fn post(app: &Router, headers: &[(String, String)], body: Vec<u8>) -> Answer {
    let mut request = Request::builder().method("POST").uri("/v1/customers");
    for (name, value) in headers {
        request = request.header(name, value);
    }
    let response = app
        .clone()
        .oneshot(request.body(Body::from(body)).expect("a request"))
        .await
        .expect("the router answers");
    Answer {
        status: response.status().as_u16(),
        headers: sorted(response.headers()),
        body: axum::body::to_bytes(response.into_body(), 1 << 20)
            .await
            .expect("a body")
            .to_vec(),
    }
}

fn golden_request() -> (Vec<(String, String)>, Vec<u8>) {
    let headers = GOLDEN_REQUEST_HEADERS
        .iter()
        .map(|(n, v)| ((*n).to_owned(), (*v).to_owned()))
        .collect();
    (headers, hex::decode(GOLDEN_REQUEST_BODY_HEX).expect("hex"))
}

fn app(now: i64) -> (Router, Seen) {
    let seen: Seen = Arc::default();
    (
        server(now, public_of(&MERCHANT_SEED), Arc::clone(&seen)),
        seen,
    )
}

#[tokio::test]
async fn cratestack_client_envelope_seals_the_bytes_0_16_0_sealed() {
    let sealed = seal(&MERCHANT_SEED).await;
    let (golden_headers, golden_body) = golden_request();
    assert_eq!(
        hex::encode(&sealed.body),
        hex::encode(&golden_body),
        "the sealed request body differs from the 0.16.0 vector: a wire break"
    );
    assert_eq!(sealed.headers, golden_headers, "the request headers differ");
}

#[tokio::test]
async fn cratestack_envelope_layer_opens_a_0_16_0_request_and_answers_the_0_16_0_bytes() {
    let (golden_headers, golden_body) = golden_request();
    let (app, seen) = app(NOW);
    let answer = post(&app, &golden_headers, golden_body).await;

    assert_eq!(answer.status, 201);
    assert_eq!(hex::encode(&answer.body), GOLDEN_RESPONSE_BODY_HEX);
    let golden: Vec<(String, String)> = GOLDEN_RESPONSE_HEADERS
        .iter()
        .map(|(n, v)| ((*n).to_owned(), (*v).to_owned()))
        .collect();
    assert_eq!(answer.headers, golden);

    // And the handler saw the plain form request the seal wrapped.
    let saw = seen.lock().expect("lock").clone();
    assert!(saw.contains(&("path".to_owned(), "/v1/customers".to_owned())));
    assert!(saw.contains(&("idempotency-key".to_owned(), "idem_golden".to_owned())));
    assert!(saw.contains(&("content-type".to_owned(), FORM.to_owned())));
    assert!(saw.contains(&("body".to_owned(), BODY.to_owned())));
}

#[tokio::test]
async fn cratestack_client_envelope_opens_a_0_16_0_answer_under_the_pinned_key() {
    let sealed = seal(&MERCHANT_SEED).await;
    let headers: HeaderMap = GOLDEN_RESPONSE_HEADERS
        .iter()
        .map(|(n, v)| {
            (
                n.parse::<axum::http::HeaderName>().expect("a name"),
                v.parse::<axum::http::HeaderValue>().expect("a value"),
            )
        })
        .collect();
    let opened = sealed
        .pending
        .open(
            201,
            &headers,
            hex::decode(GOLDEN_RESPONSE_BODY_HEX).expect("hex").into(),
        )
        .await
        .expect("a 0.16.0 answer opens");
    assert_eq!(opened.body.as_ref(), ANSWER_JSON.as_bytes());
}

/// An answer sealed for another request does not open: the response binds the
/// digest of the request it answers, so a captured answer cannot be replayed to
/// a different call.
#[tokio::test]
async fn a_0_16_0_answer_does_not_open_for_another_request() {
    let sealed = SealCall::new(
        "POST",
        RouteRef::new("/customers", &[]),
        contract_digest("POST", "/customers"),
    )
    .payload(b"phone=%2B237699999999", FORM)
    .accept("application/json")
    .idempotency_key("idem_other");
    let other = client_envelope(&MERCHANT_SEED)
        .seal_call(sealed)
        .await
        .expect("seals");
    let headers: HeaderMap = GOLDEN_RESPONSE_HEADERS
        .iter()
        .map(|(n, v)| (n.parse().expect("a name"), v.parse().expect("a value")))
        .collect();
    let refused = other
        .pending
        .open(
            201,
            &headers,
            hex::decode(GOLDEN_RESPONSE_BODY_HEX).expect("hex").into(),
        )
        .await;
    assert!(refused.is_err(), "an answer for another request opened");
}

#[tokio::test]
async fn the_golden_request_is_refused_the_second_time() {
    let (golden_headers, golden_body) = golden_request();
    let (app, seen) = app(NOW);
    assert_eq!(
        post(&app, &golden_headers, golden_body.clone())
            .await
            .status,
        201
    );
    let replay = post(&app, &golden_headers, golden_body).await;
    assert_eq!(replay.status, 401, "a replayed request must be refused");
    assert_eq!(
        seen.lock()
            .expect("lock")
            .iter()
            .filter(|(k, _)| k == "path")
            .count(),
        1,
        "the handler ran once"
    );
}

#[tokio::test]
async fn the_golden_request_is_refused_outside_the_clock_skew() {
    let (golden_headers, golden_body) = golden_request();
    for now in [NOW + 301, NOW - 301] {
        let (app, seen) = app(now);
        let answer = post(&app, &golden_headers, golden_body.clone()).await;
        assert_eq!(answer.status, 401, "clock {now}");
        assert!(seen.lock().expect("lock").is_empty(), "clock {now}");
    }
    // The edge itself is inside the window.
    for now in [NOW + 300, NOW - 300] {
        let (app, _) = app(now);
        assert_eq!(
            post(&app, &golden_headers, golden_body.clone())
                .await
                .status,
            201
        );
    }
}

#[tokio::test]
async fn a_tampered_or_foreign_golden_request_is_refused_with_the_coarse_401() {
    let (golden_headers, golden_body) = golden_request();
    // The golden message is `d2 84 58 27 <39 protected> a0 55 <21 payload> 58 40
    // <64 signature>`: a flip anywhere but the payload and the signature is
    // refused by the CBOR parser before any key is consulted, so this pins the
    // two regions only signature verification can catch.
    assert_eq!(golden_body.len(), 132);
    assert_eq!(
        &golden_body[44..46],
        &[0x55, b'p'],
        "the payload starts at 45"
    );
    assert_eq!(
        &golden_body[66..68],
        &[0x58, 0x40],
        "the signature starts at 68"
    );
    let mut coarse = None;
    for (region, offset) in [("payload", 50_usize), ("signature", 100)] {
        let (app, seen) = app(NOW);
        let mut tampered = golden_body.clone();
        tampered[offset] ^= 0x01;
        let answer = post(&app, &golden_headers, tampered).await;
        assert_eq!(answer.status, 401, "a flipped {region} byte");
        assert!(
            seen.lock().expect("lock").is_empty(),
            "the handler ran for a flipped {region} byte"
        );
        coarse = Some(answer);
    }
    let coarse = coarse.expect("two regions flipped");
    // Signed by a key the server does not hold: the same answer, byte for byte.
    let seen: Seen = Arc::default();
    let stranger = server(NOW, public_of(&[0x33; 32]), Arc::clone(&seen));
    let foreign = post(&stranger, &golden_headers, golden_body.clone()).await;
    assert_eq!(foreign.status, 401);
    assert_eq!(foreign.body, coarse.body, "the refusal tells nothing apart");
    assert_eq!(foreign.headers, coarse.headers);
    assert!(seen.lock().expect("lock").is_empty());

    // Bound to another audience: refused as well.
    let envelope_other = CoseEnvelope::server(
        CoseMode::Sign1,
        Arc::new(Ed25519Signer::from_seed(&SERVER_SEED)),
        Arc::new(
            StaticVerifierResolver::new()
                .with_key(CoseVerifyKey::ed25519(&public_of(&MERCHANT_SEED)).expect("a point")),
        ),
        Arc::new(InMemoryNonceStore::new()),
    )
    .clock(|| NOW)
    .build()
    .expect("a server envelope");
    let digests: &'static [[u8; 32]] = Box::leak(Box::new([contract_digest("POST", "/customers")]));
    let rows: &'static [(&'static str, &'static [[u8; 32]])] =
        Box::leak(Box::new([("POST /customers", digests)]));
    let layer: EnvelopeLayer =
        EnvelopeLayer::builder(envelope_other, "https://other.example".to_owned(), rows)
            .binding_resolver(CustomersOnly)
            .policy(EnvelopeMode::Required)
            .payload_media_types([FORM], ["application/json"])
            .build()
            .expect("the layer builds");
    let elsewhere = Router::new()
        .fallback(|| async { StatusCode::CREATED })
        .layer(layer);
    assert_eq!(
        post(&elsewhere, &golden_headers, golden_body).await.status,
        401
    );
}
